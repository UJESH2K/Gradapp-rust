//! Hardware detection and port selection for GradApp 2.
//!
//! A faithful Rust port of `desktop/engine/hardware.py`, in the same two halves:
//!
//! * [`detect`] gathers [`DeviceFacts`]: it shells out to `nvidia-smi`, the
//!   Windows video-controller list (PowerShell CIM), `lspci` / sysfs and the
//!   macOS system tools. Every external command has a timeout and a failure
//!   only ever means "not found". The text each command prints is handed to a
//!   pure parser in [`parse`], so every parser is unit tested against captured
//!   output.
//! * [`select_profile`] / [`host_profile`] are pure functions from those facts
//!   to a [`Profile`] naming the **port** to install (`cuda-cu130`,
//!   `cuda-cu126`, `cuda-cu128`, `xpu`, `mps`, `cpu`, experimental `rocm`).
//!   Their outcome is checked case by case against the Python original by the
//!   parity test in `tests/parity.rs` (fixtures generated by
//!   `tests/fixtures/gen_parity.py`).
//!
//! ```no_run
//! let facts = gm_probe::detect();
//! let profile = gm_probe::select_profile(&facts, gm_probe::Prefer::Auto);
//! println!("{}", gm_probe::summary(&facts));
//! println!("port {} ({})", profile.port, profile.reason);
//! ```

mod detect;
